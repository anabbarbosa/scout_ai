"""Claude access through the Claude Agent SDK, authenticated with the Claude subscription.

The SDK drives the Claude Code CLI, which uses the account logged in with `claude login`
(or the CLAUDE_CODE_OAUTH_TOKEN generated by `claude setup-token` for unattended runs).
If ANTHROPIC_API_KEY is set, the CLI uses it instead and bills the API, so we refuse to run.
"""

import os

from claude_agent_sdk import AssistantMessage, ClaudeAgentOptions, ResultMessage, TextBlock, query

from scout_ai.config import get_settings

SUMMARY_MODEL = "claude-sonnet-5-5"
RECOMMENDATION_MODEL = "claude-opus-5-5"


class LLMError(RuntimeError):
    pass


async def complete(prompt: str, *, model: str = SUMMARY_MODEL, system: str | None = None) -> str:
    """Send a single prompt with no tools and return Claude's text reply."""
    if os.environ.get("ANTHROPIC_API_KEY"):
        raise LLMError("ANTHROPIC_API_KEY is set; unset it to use the Claude subscription.")

    env: dict[str, str] = {}
    token = get_settings().claude_code_oauth_token
    if token is not None:
        env["CLAUDE_CODE_OAUTH_TOKEN"] = token.get_secret_value()

    options = ClaudeAgentOptions(
        model=model,
        system_prompt=system,
        tools=[],
        max_turns=1,
        setting_sources=[],
        env=env,
    )
    parts: list[str] = []
    async for message in query(prompt=prompt, options=options):
        if isinstance(message, AssistantMessage):
            parts.extend(block.text for block in message.content if isinstance(block, TextBlock))
        elif isinstance(message, ResultMessage) and message.is_error:
            raise LLMError(f"Claude request failed: {message.result or message.subtype}")
    return "".join(parts)
